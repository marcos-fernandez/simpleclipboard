import Testing
@testable import ClipboardCore

/// The classifier is the only thing standing between a copied password and the
/// on-disk history, so each rule is pinned explicitly.
struct PasteboardClassifierTests {
    let plainText: Set<String> = ["public.utf8-plain-text"]

    /// The classifier with the lists of a new install, which is what most tests are about.
    private func classify(
        types: Set<String>,
        sourceBundleID: String?,
        recentSourceBundleIDs: Set<String> = [],
        concealedSourceBundleIDs: Set<String> = Config.concealedSourceBundleIDs,
        ignoredSourceBundleIDs: Set<String> = Config.ignoredSourceBundleIDs
    ) -> Classification {
        PasteboardClassifier.classify(
            types: types,
            sourceBundleID: sourceBundleID,
            recentSourceBundleIDs: recentSourceBundleIDs,
            concealedSourceBundleIDs: concealedSourceBundleIDs,
            ignoredSourceBundleIDs: ignoredSourceBundleIDs
        )
    }

    @Test func plainCopyFromRegularAppIsNormal() {
        #expect(classify(types: plainText, sourceBundleID: "com.apple.Safari") == .normal)
    }

    @Test func concealedMarkerMakesItemConcealedWhateverTheSource() {
        // 1Password's browser extension copies from the browser, not from 1Password.
        let types = plainText.union([Config.concealedType])
        #expect(classify(types: types, sourceBundleID: "com.apple.Safari") == .concealed)
    }

    @Test func copyFrom1PasswordWithoutMarkerIsStillConcealed() {
        #expect(classify(types: plainText, sourceBundleID: "com.1password.1password") == .concealed)
    }

    @Test(arguments: [Config.transientType, Config.autoGeneratedType])
    func transientAndAutoGeneratedAreIgnored(type: String) {
        #expect(classify(types: plainText.union([type]), sourceBundleID: nil) == .ignore)
    }

    @Test func transientWinsOverConcealed() {
        // Nothing transient should ever be stored, not even for 10 minutes.
        let types = plainText.union([Config.transientType, Config.concealedType])
        #expect(classify(types: types, sourceBundleID: nil) == .ignore)
    }

    @Test func keychainAccessIsIgnored() {
        #expect(classify(types: plainText, sourceBundleID: "com.apple.keychainaccess") == .ignore)
    }

    @Test func appsOfTheGivenListAreIgnoredInsteadOfTheDefaultOnes() {
        // The list of the settings: an app added to it is ignored, and one removed from it is recorded again.
        let ignored: Set<String> = ["com.apple.Notes"]
        #expect(classify(
            types: plainText, sourceBundleID: "com.apple.Notes", ignoredSourceBundleIDs: ignored
        ) == .ignore)
        #expect(classify(
            types: plainText, sourceBundleID: "com.apple.Safari", recentSourceBundleIDs: ["com.apple.Notes"],
            ignoredSourceBundleIDs: ignored
        ) == .ignore)
        #expect(classify(
            types: plainText, sourceBundleID: "com.apple.keychainaccess", ignoredSourceBundleIDs: ignored
        ) == .normal)
    }

    @Test func aPasswordManagerOfTheGivenListIsIgnoredNotConcealed() {
        // Added by the user to "Ignored Apps": nothing is stored, not even in memory for 10 minutes.
        let ignored: Set<String> = ["com.1password.1password"]
        #expect(classify(
            types: plainText, sourceBundleID: "com.1password.1password", ignoredSourceBundleIDs: ignored
        ) == .ignore)
        #expect(classify(
            types: plainText.union([Config.concealedType]), sourceBundleID: "com.1password.1password",
            ignoredSourceBundleIDs: ignored
        ) == .ignore)
    }

    @Test func appsOfTheGivenSecuredListAreConcealedInsteadOfTheDefaultOnes() {
        let secured: Set<String> = ["com.apple.Notes"]
        #expect(classify(
            types: plainText, sourceBundleID: "com.apple.Notes", concealedSourceBundleIDs: secured
        ) == .concealed)
        #expect(classify(
            types: plainText, sourceBundleID: "com.apple.Safari", recentSourceBundleIDs: ["com.apple.Notes"],
            concealedSourceBundleIDs: secured
        ) == .concealed)
        #expect(classify(
            types: plainText, sourceBundleID: "com.1password.1password", concealedSourceBundleIDs: secured
        ) == .normal)
    }

    @Test func theConcealedMarkConcealsWhateverTheSecuredList() {
        // 1Password removed from "Secured Apps" still marks what it copies.
        #expect(classify(
            types: plainText.union([Config.concealedType]), sourceBundleID: "com.1password.1password",
            concealedSourceBundleIDs: []
        ) == .concealed)
    }

    @Test func ownPasteMarkerIsIgnoredSoPastesAreNotReRecorded() {
        let types = plainText.union([Config.ownMarkerType])
        #expect(classify(types: types, sourceBundleID: nil) == .ignore)
    }

    @Test func finderFileCopyIsIgnoredInsteadOfStoringTheFileName() {
        // Review focus 2: Finder puts the file name as plain text next to the file URL.
        let types = plainText.union([Config.fileURLType])
        #expect(classify(types: types, sourceBundleID: "com.apple.finder") == .ignore)
    }

    @Test func copyRightAfter1PasswordLostFocusIsStillConcealed() {
        // The monitor polls every 0.5 s: by then 1Password may have handed focus back
        // to the browser, and a password without the marker must not reach disk.
        let result = classify(
            types: plainText,
            sourceBundleID: "com.apple.Safari",
            recentSourceBundleIDs: ["com.1password.1password"]
        )
        #expect(result == .concealed)
    }

    @Test func copyFromApplePasswordsAppIsConcealed() {
        // Apple's Passwords app does not put the concealed marker on the pasteboard, so
        // without its bundle ID a copied password would be saved as plain text and synced.
        #expect(classify(types: plainText, sourceBundleID: "com.apple.Passwords") == .concealed)
    }

    @Test func copyRightAfterApplePasswordsLostFocusIsStillConcealed() {
        // Same polling race as with 1Password: focus may already be back on another app.
        let result = classify(
            types: plainText,
            sourceBundleID: "com.apple.Safari",
            recentSourceBundleIDs: ["com.apple.Passwords"]
        )
        #expect(result == .concealed)
    }

    @Test func copyRightAfterKeychainAccessLostFocusIsIgnored() {
        // Same polling race: a password copied in Keychain Access and ⌘Tab within 0.5 s must not reach disk.
        let result = classify(
            types: plainText,
            sourceBundleID: "com.apple.Safari",
            recentSourceBundleIDs: ["com.apple.keychainaccess"]
        )
        #expect(result == .ignore)
    }

    @Test func recentlyDeactivatedIgnoredAppWinsOverConcealed() {
        // Ignored means not stored at all, not even in memory for 10 minutes.
        let concealedTypes = plainText.union([Config.concealedType])
        #expect(classify(
            types: concealedTypes,
            sourceBundleID: "com.apple.Safari",
            recentSourceBundleIDs: ["com.apple.keychainaccess"]
        ) == .ignore)
        #expect(classify(
            types: plainText,
            sourceBundleID: "com.apple.Safari",
            recentSourceBundleIDs: ["com.1password.1password", "com.apple.keychainaccess"]
        ) == .ignore)
    }
}
